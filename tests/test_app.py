 def test_relationship_questions_answer_the_requested_topic(self):
  c=astro.calculate(self.profile(),datetime(2026,9,30,tzinfo=timezone.utc))
  for n in [1,9,10]:
   for question in ['when i get married','When will I marry?','What year is my wedding?','मेरी शादी कब होगी','shaadi kab hogi']:
    text=astro.reading(c,question,n)
    self.assertTrue(text.startswith('Marriage timing:'))
    self.assertIn('not a predicted wedding date',text)
    self.assertIn(f'Relationships in D{n}',text)
    self.assertNotIn('Learning:',text)
    self.assertNotIn('Career:',text)
    ruler=astro.RULERS[(c['charts'][str(n)]['ascendant_index']+6)%12]
    placement=next(p for p in c['charts'][str(n)]['planets'] if p['name']==ruler)
    self.assertIn(f"{ruler} is in {placement['sign']}, house {placement['house']}",text)
  self.assertTrue(astro.reading(c,'Tell me about my spouse').startswith('Relationships in D1'))
 def test_timing_candidates_and_topic_routing(self):
  c=astro.calculate(self.profile(),datetime(2026,9,30,tzinfo=timezone.utc))
  c['timing_analysis']=timing.build(c)
  for topic in timing.TOPICS:
   data=c['timing_analysis'][topic]
   self.assertEqual(data['rule_version'],'editorial-screen-v1')
   start=datetime.fromisoformat(data['horizon_start']);end=datetime.fromisoformat(data['horizon_end'])
   for w in data['windows']:
    self.assertLess(datetime.fromisoformat(w['start']),datetime.fromisoformat(w['end']))
    self.assertGreaterEqual(datetime.fromisoformat(w['start']),start)
    self.assertLessEqual(datetime.fromisoformat(w['end']),end)
    self.assertTrue(w['reasons'])
    for sample in w['transit_samples']:
     self.assertGreaterEqual(sample['date'],w['start']);self.assertLess(sample['date'],w['end'])
     for match in sample['matches']:
      index=astro.SIGNS.index(match['sign'])
      offsets=[0,4,6,8] if match['planet']=='Jupiter' else [0,2,6,9]
      self.assertTrue(all(astro.SIGNS.index(target) in [(index+offset)%12 for offset in offsets] for target in match['target_signs']))
  with patch.object(timing,'transit_samples',side_effect=AssertionError('Reuse cached timing analysis')):
   self.assertIn('Traditional candidate periods',astro.reading(c,'when i get married'))
   wealth=astro.reading(c,'When will I be rich?',2)
   self.assertIn('Money and wealth timing',wealth);self.assertIn('D2 Hora',wealth)
   self.assertNotIn('Career:',wealth)
  combined=astro.reading(c,'marriage and wealth timing')
  self.assertIn('Marriage timing',combined);self.assertIn('Money and wealth timing',combined)
  self.assertIn('Basic mode did not recognize',astro.reading(c,'Will I win a lottery?'))
  self.assertIn('D1 Moon:',astro.reading(c,'Where is my Moon?'))
  self.assertIn('cannot diagnose',astro.reading(c,'health and money'))
  self.assertNotIn('Career:',astro.reading(c,'money',9))
  empty=dict(c,dashas={'timeline':[]})
  self.assertEqual(timing.analyze(empty,'marriage',[])['windows'],[])
  dates=list(timing.monthly_dates(datetime(2026,12,20,tzinfo=timezone.utc),datetime(2027,2,1,tzinfo=timezone.utc)))
  self.assertEqual([d.strftime('%Y-%m-%d') for d in dates],['2026-12-20','2027-01-01'])
 def test_bilingual_translation_preserves_chart_facts(self):
  import hindi
  c=astro.calculate(self.profile(),datetime(2026,9,30,tzinfo=timezone.utc));c['timing_analysis']=timing.build(c)
  with patch.object(app_server.pipeline,'ollama',side_effect=AssertionError('Hindi facts must not be generated by a model')):
   summary=hindi.summary(c,'Explain Moon',1)
   moon=next(p for p in c['planets'] if p['name']=='Moon')
   self.assertIn(hindi.SIGNS[moon['sign']],summary)
   self.assertIn(f"भाव {moon['house']}",summary)
   result=app_server.localized_result({'text':'English interpretation','grounded_hi':summary},'both')
   self.assertEqual(result['translations']['hi'],summary)
   self.assertEqual(result['mode'],'grounded_hindi')
   unrelated=app_server.localized_result({'text':'Invent a wedding date'},'hi')
   self.assertNotIn('hi',unrelated['translations'])
   self.assertEqual(unrelated['text'],'Invent a wedding date')
  marriage=hindi.summary(c,'when i get married')
  for w in c['timing_analysis']['marriage']['windows'][:3]:
   self.assertIn(w['start'][:10],marriage);self.assertIn(w['end'][:10],marriage)
  self.assertIn('पक्की तारीख नहीं',marriage)
  self.assertIsNone(hindi.summary(c,'Will I win a lottery?'))
  self.assertEqual(app_server.translate_text('Explain my Moon placement briefly'),hindi.QUESTIONS['Explain my Moon placement briefly'])
 def test_llm_summary_uses_selected_facts_and_conversation(self):
  c=astro.calculate(self.profile(),datetime(2026,9,30,tzinfo=timezone.utc));c['timing_analysis']=timing.build(c)
  with patch.dict(os.environ,{'OLLAMA_MODEL':'test-local-model'}),patch.object(app_server.pipeline,'ollama',return_value={'message':{'content':'A concise relationship answer.'}}) as model:
   result=app_server.english_answer(c,'when i get married',[{'role':'user','content':'Earlier question'}],division=9)
   self.assertEqual(result['mode'],'llm')
   payload=model.call_args.args[1];context=json.loads(payload['messages'][-1]['content'])
   self.assertEqual(context['chart_facts']['selected_division'],9)
   self.assertEqual(context['question'],'when i get married')
   self.assertEqual(context['recent_conversation'][0]['content'],'Earlier question')
   self.assertNotIn('charts',context['chart_facts'])
   self.assertEqual(payload['options']['num_predict'],450)
   self.assertEqual(set(context['chart_facts']['marriage_charts']),{'1','9'})
   self.assertEqual(len(context['chart_facts']['timing_analysis']['marriage']['placements']),2)
   app_server.english_answer(c,'Then tell the reason and give time',[{'role':'user','content':'When could I get married?'}],division=10)
   follow=json.loads(model.call_args.args[1]['messages'][-1]['content'])
