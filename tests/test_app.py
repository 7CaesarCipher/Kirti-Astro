 def test_api_flow_isolation_and_delete(self):
  server=ThreadingHTTPServer(('127.0.0.1',0),Handler);threading.Thread(target=server.serve_forever,daemon=True).start();base='http://127.0.0.1:'+str(server.server_port)
  def post(path,data,token=''):
   req=urllib.request.Request(base+path,data=json.dumps(data).encode(),headers={'Content-Type':'application/json','Authorization':'Bearer '+token});return json.load(urllib.request.urlopen(req))
  try:
   html=urllib.request.urlopen(base).read();self.assertIn(b'Generate my reading',html);self.assertNotIn(b'Research mode',html)
   r=post('/api/reading',{'name':'Test','date':'1989-10-15','time':'20:30','place_id':places.LOCAL['id']});self.assertEqual(r['answer']['mode'],'basic')
   with self.assertRaises(urllib.error.HTTPError):post('/api/chat',{'question':'money'},'wrong-token')
   follow=post('/api/chat',{'question':'money'},r['token']);self.assertIn('Mercury',follow['text'])
   for n in astro.VARGAS:
    chosen=post('/api/chart-reading',{'division':n},r['token'])
    self.assertIn(f'D{n}',chosen['text'])
    if n!=1:
     for planet in r['chart']['charts'][str(n)]['planets']:
      self.assertIn(f"{planet['name']}: {planet['sign']}, house {planet['house']}",chosen['text'])
   with self.assertRaises(urllib.error.HTTPError):post('/api/chart-reading',{'division':5},r['token'])
   with self.assertRaises(urllib.error.HTTPError):post('/api/chart-reading',{'division':9},'wrong-token')
   follow=post('/api/chat',{'question':'overview','division':9},r['token']);self.assertIn('D9',follow['text'])
   with patch.object(app_server,'translate_text',return_value='हिंदी उत्तर'), patch.object(astro,'calculate',side_effect=AssertionError('Translation must reuse chart')), patch.object(app_server,'english_answer',side_effect=AssertionError('Translate original answer only')):
    translated=post('/api/translate',{'text':'Original answer','language':'both'},r['token'])
    self.assertEqual(translated['translations'],{'en':'Original answer','hi':'हिंदी उत्तर'})
   with self.assertRaises(urllib.error.HTTPError):post('/api/translate',{'text':'test','language':'fr'},r['token'])
   with self.assertRaises(urllib.error.HTTPError):post('/api/translate',{'text':'test','language':'hi'},'wrong-token')
   def stream(path,data):
    req=urllib.request.Request(base+path,data=json.dumps(data).encode(),headers={'Content-Type':'application/json','Authorization':'Bearer '+r['token']})
    with urllib.request.urlopen(req) as res:
     self.assertIn('application/x-ndjson',res.headers['Content-Type'])
     return [json.loads(line) for line in res if line.strip()]
   with patch.dict(os.environ,{'OLLAMA_MODEL':'test-local-model'}),patch.object(app_server.pipeline,'ollama_stream',return_value=iter(['Mars is ', 'in Gemini, house 2.'])):
    events=stream('/api/chat-stream',{'question':'Explain Mars','division':1,'language':'both'})
    self.assertEqual(events[-1]['type'],'done')
    self.assertEqual(events[-1]['answer']['translations']['en'],'Mars is in Gemini, house 2.')
    self.assertIn('hi',events[-1]['answer']['translations'])
    self.assertGreater(len([e for e in events if e['type']=='delta']),2)
    self.assertEqual(app_server.SESSIONS[r['token']]['history'][-1]['content'],'Mars is in Gemini, house 2.')
   with patch.dict(os.environ,{'OLLAMA_MODEL':'test-local-model'}),patch.object(app_server.pipeline,'ollama_stream',return_value=iter(['प्रश्न 3'])):
    events=stream('/api/translate-stream',{'text':'Question 2','language':'hi'})
    self.assertNotIn('hi',events[-1]['answer']['translations'])
    self.assertEqual(events[-1]['answer']['text'],'Question 2')
   app_server.SESSIONS[r['token']]['expires']=__import__('time').time()+5
   with patch.object(astro,'calculate',side_effect=AssertionError('Chat must reuse the chart')):
    for i in range(15):
     response=post('/api/chat',{'question':f'Explain career {i}','division':10},r['token'])
     self.assertIn('D10',response['text'])
   self.assertGreater(app_server.SESSIONS[r['token']]['expires'],__import__('time').time()+3500)
   self.assertLessEqual(len(app_server.SESSIONS[r['token']]['history']),12)
   self.assertTrue(post('/api/forget',{},r['token'])['deleted'])
   with self.assertRaises(urllib.error.HTTPError):post('/api/chat',{'question':'money'},r['token'])
  finally:server.shutdown();server.server_close()
